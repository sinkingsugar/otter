"""The VM suite's workloads: generated scripts in the 1.x dialect, their
2.0 translation, and the check of a run's output. Shared by the matched
benchmark (`run.py`) and the instruction gate (`bench/instructions`).
Python 3 standard library only."""

import json
import math
import re

VALUES = {
    "int": "7",
    "string": json.dumps("abcdefgh" * 32),
    "seq": "[" + " ".join(str(i) for i in range(64)) + "]",
    "table": "{" + " ".join(f"k{i}: {i}" for i in range(16)) + "}",
}
CASES = [f"{op}-{kind}" for op in ("const", "get", "update", "assign") for kind in VALUES]
CASES += ["add-int", "add-float", "add-float4", "take-seq", "take-table", "do-int", "push-shared-seq", "make-seq", "make-table"]


def workload(case, width):
    """Return setup, body, expected result, extra wires. Width counts motifs."""
    op, kind = case.split("-", 1)
    extra = ""
    if op in ("const", "get", "update", "assign"):
        seed = VALUES[kind]
        unit = {"const": seed, "get": "Get(seed)", "update": "Update(slot)",
                "assign": "Get(seed) | Update(slot)"}[op]
        setup = f"{seed} | Set(seed)\n{seed} | Set(slot)\n{seed} | Set(result)"
        prefix, suffix, expected = "Get(seed)", "", seed
    elif case == "add-float4":
        # Both frontends support conversion; 2.0 does not yet lower @f4.
        setup = ("[1.0 2.0 3.0 4.0] | ToFloat4 | Set(seed)\n"
                 "Get(seed) | Set(result)\n"
                 "[1.0 1.0 1.0 1.0] | ToFloat4 | Set(delta)\n"
                 f"[{width+1}.0 {width+2}.0 {width+3}.0 {width+4}.0] | ToFloat4 | Set(expected)")
        prefix, unit, suffix, expected = "Get(seed)", "Math.Add(delta)", "", "expected"
    elif op == "add" or case == "do-int":
        seed = "1.0" if kind == "float" else "1"
        arg = seed
        unit = f"Math.Add({arg})"
        if op == "do":
            extra = "@wire(step { Math.Add(1) })"
            unit = "Do(step)"
        expected = str(width + 1) + (".0" if kind == "float" else "")
        setup = f"{seed} | Set(seed)\n{seed} | Set(result)"
        prefix, suffix = "Get(seed)", ""
    elif op == "take":
        seed = VALUES[kind]
        key = '"k7"' if kind == "table" else "7"
        setup = f"{seed} | Set(seed)\n0 | Set(result)"
        prefix, unit, suffix = "0", f"Get(seed) | Take({key})", ""
        expected = "7" if width else "0"
    elif case == "push-shared-seq":
        seed = VALUES["seq"]
        setup = f"{seed} | Set(seed)\n{seed} | Set(items)\n{seed} | Set(result)"
        prefix, unit, suffix = "Get(seed) | Update(items) | 1", "Push(items Clear: false)", "Get(items)"
        expected = "[" + " ".join([*(str(i) for i in range(64)), *(["1"] * width)]) + "]"
    elif op == "make":
        unit = "[seed seed seed seed]" if kind == "seq" else "{a: seed b: seed c: seed d: seed}"
        literal = "[7 7 7 7]" if kind == "seq" else "{a: 7 b: 7 c: 7 d: 7}"
        setup = f"7 | Set(seed)\n{literal} | Set(result)"
        prefix, suffix, expected = literal, "", literal
    else:
        raise ValueError(case)
    body = " | ".join(part for part in [prefix, *([unit] * width), suffix, "Update(result)"] if part)
    return setup, body, expected, extra


def script(case, width, iterations, batches, timed=True):
    """The workload's script. Untimed (for the instruction gate), it reads no
    clock and logs no duration, so its output does not vary between runs."""
    setup, body, expected, extra = workload(case, width)
    start = "\n    Time.Now | Set(t0)" if timed else ""
    stop = '\n    Time.Now | Math.Subtract(t0) | Log("VM_SECONDS")' if timed else ""
    # Both Repeat implementations reset the action input on every iteration.
    # All setup, printing, equality checks and compilation are outside timing.
    return f"""// Generated by bench/vm-execution/workloads.py: {case}, width={width}
@mesh(root)
{extra}
@wire(main {{
  {setup}
  0 | Set(done)
  Repeat({{
    0 | Update(done){start}
    Repeat({{
      {body}
      Inc(done)
    }} Times: {iterations}){stop}
    Get(result) | Is({expected}) | Log("VM_VALID")
    Get(done) | Log("VM_DONE")
  }} Times: {batches})
}})
@schedule(root main)
@run(root)
"""


def dialect(text, engine):
    """The same workload in an engine's syntax. Scripts are written in the
    1.x dialect; 2.0 declares with Var, labels lowercase, Push neither
    declares nor clears, and a named sub-flow is a function (`Do` is gone)."""
    if engine == "1x":
        return text
    return (text.replace("Push(items Clear: false)", "Push(items)")
            .replace(" | Set(", " | Var(").replace("Times:", "times:")
            .replace("@wire(step { Math.Add(1) })", "@fn(Step input: Int output: Int params: {} { Math.Add(1) })")
            .replace("Do(step)", "Step"))


def parse_output(output, iterations, batches, timed=True):
    """Checks every batch's result and iteration count; returns the timed
    batches' durations in seconds (none for an untimed script)."""
    seconds = re.findall(r"VM_SECONDS: ([^\r\n]+)", output)
    valid = re.findall(r"VM_VALID: (\w+)", output)
    done = re.findall(r"VM_DONE: (\d+)", output)
    if len(seconds) != (batches if timed else 0) or valid != ["true"] * batches or done != [str(iterations)] * batches:
        raise RuntimeError(f"missing samples or incorrect work/result: {output[-6000:]}")
    try:
        values = [float(s) for s in seconds]
    except ValueError as error:
        raise RuntimeError(f"invalid durations: {seconds}") from error
    if not all(math.isfinite(s) and s > 0 for s in values):
        raise RuntimeError(f"invalid durations: {values}")
    return values
